"""읽어 주기 숫자 → 한글 (PM 11/2): 금액·수량을 사람이 말하는 대로, 이름·번호는 그대로."""

import pytest

from app.services.tts_numbers import korean_numbers


@pytest.mark.parametrize(("text", "spoken"), [
    # 화면 문장 그대로
    ("가나상회, 8,000원, 미수금. 이 내용이 맞나요?", "가나상회, 팔천 원, 미수금. 이 내용이 맞나요?"),
    ("합계가 12,000원이에요, 15,000원이에요?", "합계가 만 이천 원이에요, 만 오천 원이에요?"),
    ("한 번에 품목은 3개까지 입력할 수 있습니다.", "한 번에 품목은 세 개까지 입력할 수 있습니다."),
    ("1번째 품목은 몇 개예요?", "첫 번째 품목은 몇 개예요?"),
    ("2번째 품목", "두 번째 품목"),
    # 금액 자리
    ("1원", "일 원"),
    ("10원", "십 원"),
    ("110원", "백십 원"),
    ("1,000원", "천 원"),
    ("10,000원", "만 원"),
    ("11,000원", "만 천 원"),
    ("20,000원", "이만 원"),
    ("2,500,000원", "이백오십만 원"),
    ("100,000,000원", "일억 원"),
    ("100,010,000원", "일억 만 원"),
    ("0원", "영 원"),
    ("8000 원", "팔천 원"),
    # 세는 말은 고유어, 무게·분량은 한자어
    ("배추 3박스", "배추 세 박스"),
    ("대파 2단", "대파 두 단"),
    ("두부 20모", "두부 스무 모"),
    ("계란 21판", "계란 스물한 판"),
    ("사과 99개", "사과 아흔아홉 개"),
    ("사과 100개", "사과 백 개"),
    ("거래처 2곳", "거래처 두 곳"),
    ("고기 5킬로", "고기 오 킬로"),
    ("쌀 3kg", "쌀 삼 kg"),
    ("국밥 2인분", "국밥 이 인분"),
    ("1.5박스", "일 점 오 박스"),
    ("0.5단", "영 점 오 단"),
    # 단위 없는 숫자
    ("5월 3일", "오월 삼일"),
    ("5", "오"),
])
def test_numbers_read_as_spoken_korean(text: str, spoken: str) -> None:
    assert korean_numbers(text) == spoken


@pytest.mark.parametrize("text", [
    "이 내용이 맞나요?",
    "마바분식 대파 팔천 원 외상이요. 몇 단이었어요?",
    "B2B상회",  # 낱말 일부
    "010-1234-5678",  # 번호
    "123-45-67890",
    "007상회",  # 0으로 시작
    "12345678901234567890",  # 금액이 아닌 긴 숫자
])
def test_other_text_stays_as_written(text: str) -> None:
    assert korean_numbers(text) == text


@pytest.mark.parametrize(("text", "spoken"), [
    ("3단지식당", "삼단지식당"),
    ("1번가식당", "일번가식당"),
])
def test_name_with_a_number_is_not_read_as_a_count(text: str, spoken: str) -> None:
    assert korean_numbers(text) == spoken
